"""

Shared Pydantic models used throughout the Restaurant
Operations Intelligence Agent workflow.

These models define the contracts exchanged between
agents and the final workflow output generated by
the Inventory Orchestrator Agent.
"""

from typing import Literal

from pydantic import BaseModel, Field
from libs.manager_input import ManagerDecision


# Metrics Models

class TokenUsage(BaseModel):
    """
    Trackes LLM Token Consumption

    """
    request_tokens: int = 0
    response_tokens: int = 0
    total_tokens: int = 0

    requests: int = 0

    reasoning_tokens: int = 0

    estimated_cost: float = 0.0


class WorkflowMetrics(BaseModel):
    """
    Captures operational metrics gathered during
    workflow execution.
    """
    workflow_id: str | None = None
    agents_invoked: list[str] = Field(default_factory=list)
    execution_time_seconds: float = 0.0
    token_usage: TokenUsage = Field(default_factory=TokenUsage)


# Sales Models

class SalesItem(BaseModel):
    """
    Represents a menu item sold during service.
    """

    menu_item: str
    quantity: int = Field(gt=0)


class SalesReport(BaseModel):
    """
    Structured sales report extracted from a
    natural language staff sales report.
    """

    sales: list[SalesItem]


# Inventory Models

class InventoryItem(BaseModel):
    """
    Represents a single inventory record.
    """

    ingredient_name: str
    quantity: float = Field(ge=0.0)
    unit: str
    reorder_threshold: float = Field(ge=0.0)
    days_to_expiry: int = Field(ge=0)


class InventoryAssessment(BaseModel):
    """
    Inventory health assessment returned by
    the Inventory Operations Agent.
    """

    inventory_healthy: bool

    low_stock_items: list[str] = Field(
        default_factory=list
    )

    expiry_risk_items: list[str] = Field(
        default_factory=list
    )

    summary: str


# Reorder Models

class ReorderRecommendation(BaseModel):
    """
    Recommendation produced by the Reorder Agent.
    """

    ingredient_name: str

    reorder_quantity: float = Field(gt=0)

    recommended_vendor: str

    total_cost: float = Field(ge=0)

    justification: str

# Menu Strategy Models


class MenuRecommendation(BaseModel):
    """
    Recommendation produced by the Menu Strategy Agent.
    """

    special_name: str

    ingredients_used: list[str] = Field(
        default_factory=list
    )

    reasoning: str


# Critic Models

class CriticReview(BaseModel):
    """
    Validation generated by the Operations Critic Agent.
    """

    approved: bool

    confidence_score: float = Field(
        ge=0.0,
        le=1.0
    )

    feedback: str

# Final Orchestrator Response


class OrchestratorResponse(BaseModel):
    """
    Final response generated by the Inventory
    Orchestrator.
    """

    status: Literal[
        "completed",
        "rejected",
        "error",
    ]

    inventory_healthy: bool

    summary: str

    reorder_recommendations: list[
        ReorderRecommendation
    ] = Field(default_factory=list)

    menu_recommendations: list[
        MenuRecommendation
    ] = Field(default_factory=list)

    critic_review: CriticReview | None = None

    manager_decision: ManagerDecision | None = None

    final_actions: list[str] = Field(
        default_factory=list
    )

    metrics: WorkflowMetrics | None = None
